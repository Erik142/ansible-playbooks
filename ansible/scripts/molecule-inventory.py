#!/usr/bin/env python3
"""Render each host's real non-secret group_vars for the molecule playbook scenarios.

For inventories/<host>/group_vars/all:
  - copies every *.yml except vault.yml and vault.yml.example unchanged
  - writes vault_stub.yml: every variable named in vault.yml.example, with fake values

The encrypted vault.yml is never read, so CI needs no secrets. Output goes to
collections/homelab/extensions/molecule/.generated/<host>/group_vars/all/.

Fails when a copied file references a `{{ vault_x }}` that vault.yml.example does not
define, so a new vault secret cannot silently break a scenario.

Usage: scripts/molecule-inventory.py [host ...]   (default: nas ops ci edge)
"""

import re
import shutil
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT_ROOT = REPO / "collections/homelab/extensions/molecule/.generated"
HOSTS = ["nas", "ops", "ci", "edge"]
VAULT_REF = re.compile(r"\{\{\s*(vault_[A-Za-z0-9_]+)")
SKIP = {"vault.yml", "vault.yml.example"}


def render(host: str) -> None:
    src = REPO / "inventories" / host / "group_vars" / "all"
    dst = OUT_ROOT / host / "group_vars" / "all"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)

    example = yaml.safe_load((src / "vault.yml.example").read_text()) or {}
    stub = {}
    for name, value in example.items():
        stub[name] = f"molecule-fake-{name}" if isinstance(value, str) else value

    referenced = set()
    for path in sorted(src.glob("*.yml")):
        if path.name in SKIP:
            continue
        text = path.read_text()
        referenced |= set(VAULT_REF.findall(text))
        shutil.copyfile(path, dst / path.name)

    missing = sorted(referenced - set(stub))
    if missing:
        sys.exit(f"{host}: vars reference vault names missing from vault.yml.example: {missing}")

    (dst / "vault_stub.yml").write_text(
        "# Generated by scripts/molecule-inventory.py. Fake values, never decrypted.\n"
        + yaml.safe_dump(stub, sort_keys=True)
    )
    print(f"{host}: {len(referenced)} vault refs, {len(stub)} stub vars -> {dst.relative_to(REPO)}")


if __name__ == "__main__":
    for h in sys.argv[1:] or HOSTS:
        if h not in HOSTS:
            sys.exit(f"unknown host: {h}")
        render(h)
